/**
 * Writes db/seed.sql from the local starter catalogue (src/data/catalogue.ts).
 *
 *   node scripts/build-seed-sql.ts
 *
 * Every row uses INSERT OR IGNORE with a fixed id, so seeding twice (or after
 * editors have changed things in the admin) never duplicates or overwrites.
 * Starter images point at the site's own /images/... files; nothing is uploaded.
 */
import { mkdirSync, writeFileSync } from "node:fs";

import {
  starterBrands,
  starterCategories,
  starterIndustries,
  starterProducts,
} from "../src/data/catalogue.ts";
import { defaultSiteSettings } from "../shared/site.ts";

const OUTPUT = new URL("../db/seed.sql", import.meta.url);

function sql(value: string | number | boolean | null | undefined): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
}

function insert(table: string, row: Record<string, string | number | boolean | null>) {
  const columns = Object.keys(row);
  return `INSERT OR IGNORE INTO ${table} (${columns.join(", ")}) VALUES (${columns
    .map((column) => sql(row[column]))
    .join(", ")});`;
}

const lines: string[] = [
  "-- Generated by scripts/build-seed-sql.ts from src/data/catalogue.ts. Do not edit by hand.",
  "PRAGMA foreign_keys = ON;",
  "",
];

const categoryIds = new Map<string, number>();
starterCategories.forEach((category, index) => {
  const id = index + 1;
  categoryIds.set(category.slug, id);
  lines.push(
    insert("categories", {
      id,
      parent_id: null,
      slug: category.slug,
      title: category.title,
      eyebrow: category.eyebrow,
      summary: category.summary,
      image_url: category.image,
      image_alt: `${category.title} products`,
      show_on_home: true,
      sort_order: (index + 1) * 10,
    }),
  );
});

lines.push("");
const brandIds = new Map<string, number>();
starterBrands.forEach((brand, index) => {
  const id = index + 1;
  brandIds.set(brand.slug, id);
  lines.push(
    insert("brands", {
      id,
      slug: brand.slug,
      name: brand.name,
      tagline: brand.tagline,
      description: brand.description,
      confirmed: brand.confirmed,
      in_house: false,
      logo_url: brand.logo,
      logo_alt: `${brand.name} logo`,
      sort_order: (index + 1) * 10,
    }),
  );
});

lines.push("");
starterIndustries.forEach((industry, index) => {
  lines.push(
    insert("industries", {
      id: index + 1,
      slug: industry.slug,
      title: industry.title,
      label: industry.label,
      summary: industry.summary,
      image_url: industry.image,
      image_alt: industry.title,
      show_on_home: true,
      sort_order: (index + 1) * 10,
    }),
  );
});

lines.push("");
starterProducts.forEach((product, index) => {
  const id = index + 1;
  const categoryId = categoryIds.get(product.category);
  const category = starterCategories.find((item) => item.slug === product.category);

  if (!categoryId || !category) {
    throw new Error(`Unknown category "${product.category}" for ${product.slug}`);
  }

  const brandId = product.brand ? brandIds.get(product.brand) : null;

  if (product.brand && !brandId) {
    throw new Error(`Unknown brand "${product.brand}" for ${product.slug}`);
  }

  const position = starterProducts
    .filter((item) => item.category === product.category)
    .indexOf(product);

  lines.push(
    insert("products", {
      id,
      category_id: categoryId,
      slug: product.slug,
      title: product.title,
      summary: product.summary,
      brand_id: brandId ?? null,
      is_sample: true,
      published: true,
      sort_order: (position + 1) * 10,
    }),
    // The category image stands in until product photography is supplied.
    insert("product_images", {
      id,
      product_id: id,
      image_url: category.image,
      alt: product.title,
      sort_order: 0,
    }),
  );
});

lines.push("", insert("settings", { key: "site", value: JSON.stringify(defaultSiteSettings) }), "");

mkdirSync(new URL("../db/", import.meta.url), { recursive: true });
writeFileSync(OUTPUT, lines.join("\n"));

console.log(
  `Wrote db/seed.sql: ${starterCategories.length} categories, ${starterBrands.length} brands, ${starterIndustries.length} industries, ${starterProducts.length} products`,
);
